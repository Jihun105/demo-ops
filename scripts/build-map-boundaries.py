#!/usr/bin/env python3
"""Build the bundled capital-region boundaries; requires shapely==2.1.2.

Usage: python build-map-boundaries.py downloaded-source.geojson
Source URL, SHA256 and attribution are recorded in docs/reference/map-boundaries.md.
"""
import collections
import hashlib
import json
from pathlib import Path
import re
import sys

import shapely
from shapely.geometry import mapping, shape

SOURCE_SHA = "7360288277dfd12d74e54b959c59bdd66f852e3a"
SOURCE_URL = f"https://raw.githubusercontent.com/vuski/admdongkor/{SOURCE_SHA}/ver20260701/HangJeongDong_ver20260701.geojson"
EXPECTED = set("가평 고양 과천 광명 광주 구리 군포 김포 남양주 동두천 부천 성남 수원 시흥 안산 안성 안양 양주 양평 여주 연천 오산 용인 의왕 의정부 이천 파주 평택 포천 하남 화성 서울 인천".split())
# Seoul districts by business zone; same table as SEOUL in src/ui/model.js.
SEOUL_ZONES = {
    "경기 북부": "은평 종로 서대문 성북 강북 도봉 노원 중랑 동대문".split(),
    "경기 서부": "마포 강서 양천 구로 금천 영등포 동작 관악 용산 중".split(),
    "경기 동부": "서초 강남 송파 강동 광진 성동".split(),
}


def rounded(value):
    if isinstance(value, (list, tuple)):
        return [rounded(item) for item in value]
    return round(value, 6)


def main():
    raw = Path(sys.argv[1]).read_bytes()
    groups = collections.defaultdict(list)
    seoul = collections.defaultdict(list)
    for feature in json.loads(raw)["features"]:
        props = feature["properties"]
        if props["sidonm"] == "서울특별시":
            seoul[re.sub(r"^서울특별시\s*", "", props["sggnm"])[:-1]].append(shapely.make_valid(shape(feature["geometry"])))
        if props["sidonm"] == "경기도":
            name = re.match(r"(.+?[시군])", props["sggnm"]).group(1)[:-1]
        elif props["sidonm"] == "서울특별시":
            name = "서울"
        elif props["sidonm"] == "인천광역시":
            name = "인천"
        else:
            continue
        groups[name].append(shapely.make_valid(shape(feature["geometry"])))
    assert set(groups) == EXPECTED, set(groups) ^ EXPECTED
    districts = [d for names in SEOUL_ZONES.values() for d in names]
    assert sorted(seoul) == sorted(districts), set(seoul) ^ set(districts)
    regions = {}
    area_errors = []

    def simplified_polygons(parts):
        merged = shapely.union_all(parts, grid_size=0.000001)
        simplified = merged.simplify(0.00015, preserve_topology=True)
        assert simplified.is_valid and not simplified.is_empty
        geometry = mapping(simplified)
        assert geometry["type"] in ("Polygon", "MultiPolygon")
        return rounded([geometry["coordinates"]] if geometry["type"] == "Polygon" else geometry["coordinates"])

    # Seoul split into the three business zones for the 업무 현황 map (kept apart from regions).
    seoul_zones = {zone: simplified_polygons([g for d in names for g in seoul[d]]) for zone, names in SEOUL_ZONES.items()}
    for name in sorted(groups):
        merged = shapely.union_all(groups[name], grid_size=0.000001)
        simplified = merged.simplify(0.00015, preserve_topology=True)
        assert simplified.is_valid and not simplified.is_empty
        area_errors.append(abs(simplified.area - merged.area) / merged.area)
        geometry = mapping(simplified)
        polygons = [geometry["coordinates"]] if geometry["type"] == "Polygon" else geometry["coordinates"]
        assert geometry["type"] in ("Polygon", "MultiPolygon")
        regions[name] = rounded(polygons)
        assert shape({"type": "MultiPolygon", "coordinates": regions[name]}).is_valid
        for polygon in regions[name]:
            for ring in polygon:
                assert len(ring) >= 4 and ring[0] == ring[-1]
                assert all(124 < lng < 129 and 36 < lat < 39 for lng, lat in ring)
    payload = {
        "source": "통계청 SGIS · vuski/admdongkor",
        "sourceUrl": "https://github.com/vuski/admdongkor",
        "upstreamUrl": "https://sgis.kostat.go.kr",
        "vintage": "2026-07-01",
        "retrievedAt": "2026-09-21",
        "license": "CC BY 4.0; SGIS 원자료 공공누리 제1유형",
        "licenseUrl": "https://creativecommons.org/licenses/by/4.0/",
        "attribution": "본 데이터는 통계청 통계지리정보서비스(SGIS, https://sgis.kostat.go.kr)에서 공공누리 제1유형으로 개방한 행정동 경계를 가공한 것이며(가공: vuski/admdongkor, https://github.com/vuski/admdongkor), CC BY 4.0으로 배포됩니다. 이 앱에서 시군 병합·경계 단순화를 적용했습니다.",
        "sourceFileUrl": SOURCE_URL,
        "sourceSha256": hashlib.sha256(raw).hexdigest(),
        "coordinateSystem": "EPSG:4326",
        "simplificationToleranceDegrees": 0.00015,
        "regions": regions,
        "seoulZones": seoul_zones,
    }
    output = Path(__file__).resolve().parents[1] / "src/ui/map-frame/boundaries.js"
    output.write_text("// Generated by scripts/build-map-boundaries.py; see docs/reference/map-boundaries.md.\n// Data: CC BY 4.0; retain SGIS and vuski/admdongkor attribution.\nwindow.DemoBoundaries = " + json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
    print(json.dumps({"regions": len(regions), "bytes": output.stat().st_size, "sourceSha256": payload["sourceSha256"], "maxRelativeAreaChange": max(area_errors)}, indent=2))


if __name__ == "__main__":
    main()
